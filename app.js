function bindLessonEvents() {
  document.querySelector('[data-action="close"]')?.addEventListener("click", renderHome);
  document.querySelector('[data-action="next"]')?.addEventListener("click", nextStep);
  document.querySelector('[data-action="home"]')?.addEventListener("click", renderHome);
  document.querySelector('[data-action="following"]')?.addEventListener("click", () => {
    const next = session.lesson.id + 1;
    if (next <= 26) startLesson(next); else renderHome();
  });
  const speakButton = document.querySelector('[data-action="speak"]');
  const currentStep = session.lesson.steps[session.step];
  speakButton?.addEventListener("click", () => speak(currentStep.speak, speakButton));
  document.querySelectorAll("[data-answer]").forEach(button => {
    button.addEventListener("click", () => selectAnswer(Number(button.dataset.answer)));
  });
  document.querySelector('[data-action="check"]')?.addEventListener("click", checkAnswer);
}

function nextStep() {
  session.step += 1;
  session.selected = null;
  renderLesson();
}

function selectAnswer(index) {
  if (session.locked) return;
  session.selected = index;
  document.querySelectorAll("[data-answer]").forEach((button, i) => button.classList.toggle("selected", i === index));
  document.querySelector('[data-action="check"]').disabled = false;
}

function checkAnswer() {
  if (session.locked || session.selected === null) return;
  const step = session.lesson.steps[session.step];
  const chosen = step.options[session.selected];
  const correct = chosen === step.answer;
  session.locked = true;
  session.answered += 1;
  state.a += 1;
  if (correct) {
    session.correct += 1;
    state.q += 1;
  }

  document.querySelectorAll("[data-answer]").forEach((button, index) => {
    const value = step.options[index];
    if (index === session.selected) button.classList.add(correct ? "correct" : "wrong");
    if (value !== step.answer && index !== session.selected) button.classList.add("dim");
    button.disabled = true;
  });
  const feedback = document.getElementById("feedback");
  feedback.innerHTML = `<div class="feedback ${correct ? "correct" : "wrong"}">${correct ? "Верно." : `Правильный ответ: ${step.answer}.`} ${step.note || ""}</div>`;
  const check = document.querySelector('[data-action="check"]');
  check.disabled = false;
  check.textContent = "Дальше";
  check.removeEventListener("click", checkAnswer);
  check.addEventListener("click", () => {
    session.locked = false;
    nextStep();
  }, { once: true });
  saveState();
}

function completeLesson() {
  const id = session.lesson.id;
  if (!state.c.includes(id)) state.c.push(id);
  state.c.sort((a, b) => a - b);
  state.l = Math.min(26, id + 1);
  updateStreak();
  saveState();
}

function stopSpeech() {
  activeSpeech += 1;
  if ("speechSynthesis" in window) window.speechSynthesis.cancel();
}

function speak(source, button) {
  if (!("speechSynthesis" in window)) {
    showToast("В этом браузере озвучивание недоступно");
    return;
  }

  const spec = source && typeof source === "object" && !Array.isArray(source)
    ? source
    : { items: Array.isArray(source) ? source : [source] };
  const items = (Array.isArray(spec.items) ? spec.items : [spec.items]).filter(Boolean);
  const gap = Number.isFinite(spec.gap) ? spec.gap : 650;
  if (!items.length) return;

  const token = ++activeSpeech;
  window.speechSynthesis.cancel();
  const label = button?.querySelector(".speak-label");
  const initialLabel = label?.textContent || "Послушать";
  if (button) {
    button.disabled = true;
    button.classList.add("speaking");
  }

  const finish = () => {
    if (token !== activeSpeech) return;
    if (button) {
      button.disabled = false;
      button.classList.remove("speaking");
    }
    if (label) label.textContent = initialLabel;
  };

  const playItem = index => {
    if (token !== activeSpeech) return;
    if (index >= items.length) {
      finish();
      return;
    }

    if (label && items.length > 1) label.textContent = `Слушаем ${index + 1} из ${items.length}`;
    const utterance = new SpeechSynthesisUtterance(items[index]);
    utterance.lang = "el-GR";
    utterance.rate = .78;
    const voices = window.speechSynthesis.getVoices();
    utterance.voice = voices.find(voice => voice.lang.toLowerCase().startsWith("el")) || null;
    utterance.onend = () => {
      if (token !== activeSpeech) return;
      if (index < items.length - 1) setTimeout(() => playItem(index + 1), gap);
      else finish();
    };
    utterance.onerror = finish;
    window.speechSynthesis.speak(utterance);
  };

  playItem(0);
}

function resetProgress() {
  if (!window.confirm("Сбросить весь прогресс курса? Отменить это действие не получится.")) return;
  document.cookie = `${COOKIE}=; Max-Age=0; Path=/; SameSite=Lax`;
  state = { ...DEFAULT_STATE, c: [] };
  renderHome();
  showToast("Прогресс сброшен");
}

function showToast(message) {
  document.querySelector(".toast")?.remove();
  const toast = document.createElement("div");
  toast.className = "toast";
  toast.textContent = message;
  document.body.append(toast);
  setTimeout(() => toast.remove(), 2600);
}

document.addEventListener("keydown", event => {
  if (!session || session.locked) return;
  const index = Number(event.key) - 1;
  if (index >= 0 && index <= 3 && document.querySelector(`[data-answer="${index}"]`)) selectAnswer(index);
  if (event.key === "Enter") document.querySelector('[data-action="check"]:not(:disabled), [data-action="next"]')?.click();
});

const originalRenderLesson = renderLesson;
renderLesson = function renderLessonWithCompletion() {
  if (session && session.step === session.lesson.steps.length) completeLesson();
  originalRenderLesson();
};

