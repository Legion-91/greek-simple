function loadState() {
  try {
    const part = document.cookie.split("; ").find(row => row.startsWith(`${COOKIE}=`));
    if (!part) return { ...DEFAULT_STATE };
    const parsed = JSON.parse(decodeURIComponent(part.split("=").slice(1).join("=")));
    return { ...DEFAULT_STATE, ...parsed, c: Array.isArray(parsed.c) ? parsed.c : [] };
  } catch {
    return { ...DEFAULT_STATE };
  }
}

function saveState() {
  document.cookie = `${COOKIE}=${encodeURIComponent(JSON.stringify(state))}; Max-Age=31536000; Path=/; SameSite=Lax`;
}

function updateStreak() {
  const today = new Date().toISOString().slice(0, 10);
  if (state.d === today) return;
  const yesterday = new Date(Date.now() - 86400000).toISOString().slice(0, 10);
  state.s = state.d === yesterday ? state.s + 1 : 1;
  state.d = today;
}

